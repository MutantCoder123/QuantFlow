import pandas as pd
import pandas_ta as ta
import numpy as np
from scipy.signal import argrelextrema

class MathEngine:
    @staticmethod
    def calc_trend_and_momentum(df: pd.DataFrame) -> pd.DataFrame:
        """
        Calculates core oscillators and trend guards without mutating the original state.
        Uses pandas-ta to append indicators.
        """
        # Calculate EMAs
        df['ema_9'] = ta.ema(df['close'], length=9)
        df['ema_21'] = ta.ema(df['close'], length=21)
        
        # Calculate RSI
        df['rsi_14'] = ta.rsi(df['close'], length=14)
        
        # Calculate MACD
        macd = ta.macd(df['close'], fast=12, slow=26, signal=9)
        # MACD returns MACD_12_26_9, MACDh_12_26_9, MACDs_12_26_9 by default.
        if macd is not None:
            df['macd'] = macd['MACD_12_26_9']
            df['macd_hist'] = macd['MACDh_12_26_9']
            df['macd_signal'] = macd['MACDs_12_26_9']
            
        # Calculate Bollinger Bands
        bb = ta.bbands(df['close'], length=20, std=2)
        if bb is not None:
            df['bb_lower'] = bb['BBL_20_2.0']
            df['bb_mid'] = bb['BBM_20_2.0']
            df['bb_upper'] = bb['BBU_20_2.0']
            
        # Calculate Average True Range (ATR)
        # ATR requires high, low, close
        df['atr_14'] = ta.atr(df['high'], df['low'], df['close'], length=14)
        
        # Cleanly handle NaN values generated by technical indicators
        df.bfill(inplace=True)
        # Drop any remaining NaNs if there wasn't enough data to backfill properly
        df.dropna(inplace=True)
        
        return df

    @staticmethod
    def calc_institutional_volume(df: pd.DataFrame) -> pd.DataFrame:
        """
        Calculates advanced volume metrics (Phase 2.2).
        """
        # 1. VWAP: Temporarily set datetime index if timestamp exists for anchoring
        if 'timestamp' in df.columns:
            temp_df = df.set_index('timestamp')
            vwap = ta.vwap(temp_df['high'], temp_df['low'], temp_df['close'], temp_df['volume'])
            df['vwap'] = vwap.values if vwap is not None else np.nan
        else:
            df['vwap'] = ta.vwap(df['high'], df['low'], df['close'], df['volume'])
            
        # 2. Volume Z-Score
        vol_mean = df['volume'].rolling(window=20).mean()
        vol_std = df['volume'].rolling(window=20).std()
        df['vol_z_score'] = (df['volume'] - vol_mean) / vol_std
        
        # 3. Chaikin Money Flow (CMF)
        df['cmf'] = ta.cmf(df['high'], df['low'], df['close'], df['volume'], length=20)
        
        # Cleanly handle newly generated NaN values
        df.bfill(inplace=True)
        df.dropna(inplace=True)
        
        return df

    @staticmethod
    def calc_macro_geometry(df: pd.DataFrame) -> dict:
        """
        Calculates Phase 2.3 Macro-Geometric Scanner metrics.
        Returns a dictionary of boolean flags and price levels.
        """
        geometry_payload = {
            "double_bottom": False,
            "double_top": False,
            "head_and_shoulders": False,
            "levels": {}
        }
        
        # Vector Safety: ensure enough candles to confirm peaks with order=5
        if len(df) < 50:
            return geometry_payload
            
        try:
            closes = df['close'].values
            
            # 1. Extrema Detection
            # order=5 means 5 points on each side. The last 5 candles cannot be confirmed.
            peaks_idx = argrelextrema(closes, np.greater, order=5)[0]
            valleys_idx = argrelextrema(closes, np.less, order=5)[0]
            
            # 2. Double Bottom Scanner
            if len(valleys_idx) >= 2:
                v1, v2 = closes[valleys_idx[-2]], closes[valleys_idx[-1]]
                if abs(v2 - v1) / max(v1, v2) <= 0.002:
                    geometry_payload["double_bottom"] = True
                    geometry_payload["levels"]["double_bottom_level"] = round(float((v1 + v2) / 2), 2)
                    
            # 3. Double Top Scanner
            if len(peaks_idx) >= 2:
                p1, p2 = closes[peaks_idx[-2]], closes[peaks_idx[-1]]
                if abs(p2 - p1) / max(p1, p2) <= 0.002:
                    geometry_payload["double_top"] = True
                    geometry_payload["levels"]["double_top_level"] = round(float((p1 + p2) / 2), 2)
                    
            # 4. Head & Shoulders Scanner
            if len(peaks_idx) >= 3 and len(valleys_idx) >= 2:
                p1, p2, p3 = closes[peaks_idx[-3]], closes[peaks_idx[-2]], closes[peaks_idx[-1]]
                if p2 > p1 and p2 > p3:
                    if abs(p1 - p3) / max(p1, p3) <= 0.01:
                        geometry_payload["head_and_shoulders"] = True
                        geometry_payload["levels"]["head_and_shoulders_neckline"] = round(float(min(p1, p3)), 2)
                        
        except Exception:
            pass
            
        return geometry_payload

    @staticmethod
    def generate_signal_payload(df: pd.DataFrame, token: str) -> dict:
        """
        Executes math engine on a copy of the dataframe, extracts the latest row,
        and returns a clean dictionary payload.
        """
        # Work on a copy to ensure pure function behavior
        df_copy = df.copy()
        
        # Calculate indicators
        processed_df = MathEngine.calc_trend_and_momentum(df_copy)
        processed_df = MathEngine.calc_institutional_volume(processed_df)
        geometry = MathEngine.calc_macro_geometry(processed_df)
        
        if processed_df.empty:
            return {"token": token, "error": "Not enough data"}
            
        # Extract the very last row (the active live candle)
        last_row = processed_df.iloc[-1]
        
        # Format the clean Python dictionary
        payload = {
            "token": token,
            "rsi": round(last_row.get('rsi_14', 0), 2),
            "ema_9": round(last_row.get('ema_9', 0), 2),
            "ema_21": round(last_row.get('ema_21', 0), 2),
            "macd": round(last_row.get('macd', 0), 2),
            "macd_hist": round(last_row.get('macd_hist', 0), 2),
            "macd_signal": round(last_row.get('macd_signal', 0), 2),
            "bb_lower": round(last_row.get('bb_lower', 0), 2),
            "bb_upper": round(last_row.get('bb_upper', 0), 2),
            "atr": round(last_row.get('atr_14', 0), 2),
            "vwap": round(last_row.get('vwap', 0), 2),
            "vol_z_score": round(last_row.get('vol_z_score', 0), 2),
            "cmf": round(last_row.get('cmf', 0), 2),
            "geometry": geometry
        }
        
        return payload
