import pandas as pd
import pandas_ta as ta
import numpy as np
import talib
from scipy.signal import argrelextrema

class MathEngine:
    @staticmethod
    def calc_trend_and_momentum(df: pd.DataFrame) -> pd.DataFrame:
        """
        Calculates core oscillators and trend guards without mutating the original state.
        Uses pandas-ta to append indicators.
        """
        # Calculate EMAs
        df['ema_9'] = ta.ema(df['close'], length=9)
        df['ema_21'] = ta.ema(df['close'], length=21)
        
        # Calculate RSI
        df['rsi_14'] = ta.rsi(df['close'], length=14)
        
        # Calculate MACD
        macd = ta.macd(df['close'], fast=12, slow=26, signal=9)
        # MACD returns MACD_12_26_9, MACDh_12_26_9, MACDs_12_26_9 by default.
        if macd is not None:
            df['macd'] = macd['MACD_12_26_9']
            df['macd_hist'] = macd['MACDh_12_26_9']
            df['macd_signal'] = macd['MACDs_12_26_9']
            
        # Calculate Bollinger Bands
        bb = ta.bbands(df['close'], length=20, std=2)
        if bb is not None and not bb.empty:
            df['bb_lower'] = bb.iloc[:, 0]
            df['bb_mid'] = bb.iloc[:, 1]
            df['bb_upper'] = bb.iloc[:, 2]
            
        # Calculate Average True Range (ATR)
        # ATR requires high, low, close
        df['atr_14'] = ta.atr(df['high'], df['low'], df['close'], length=14)
        
        # Cleanly handle NaN values generated by technical indicators
        df.bfill(inplace=True)
        # Drop any remaining NaNs if there wasn't enough data to backfill properly
        df.dropna(inplace=True)
        
        return df

    @staticmethod
    def calc_institutional_volume(df: pd.DataFrame) -> pd.DataFrame:
        """
        Calculates advanced volume metrics (Phase 2.2).
        """
        # 1. VWAP: Temporarily set datetime index if timestamp exists for anchoring
        if 'timestamp' in df.columns:
            temp_df = df.set_index('timestamp')
            vwap = ta.vwap(temp_df['high'], temp_df['low'], temp_df['close'], temp_df['volume'], bands=[2])
            if vwap is not None and not vwap.empty:
                df['vwap'] = vwap.iloc[:, 0].values
                df['vwap_lower'] = vwap.iloc[:, 1].values
                df['vwap_upper'] = vwap.iloc[:, 2].values
            else:
                df['vwap'], df['vwap_lower'], df['vwap_upper'] = np.nan, np.nan, np.nan
        else:
            vwap = ta.vwap(df['high'], df['low'], df['close'], df['volume'], bands=[2])
            if vwap is not None and not vwap.empty:
                df['vwap'] = vwap.iloc[:, 0]
                df['vwap_lower'] = vwap.iloc[:, 1]
                df['vwap_upper'] = vwap.iloc[:, 2]
            else:
                df['vwap'], df['vwap_lower'], df['vwap_upper'] = np.nan, np.nan, np.nan
            
        # 2. Time-of-Day (ToD) Normalized Volume Z-Score
        df['time'] = pd.to_datetime(df['timestamp']).dt.time
        
        historical_df = df.iloc[:-1] if len(df) > 1 else df
        time_stats = historical_df.groupby('time')['volume'].agg(['mean', 'std']).to_dict(orient='index')
        
        df['rolling_mean'] = df['volume'].rolling(window=20).mean()
        df['rolling_std'] = df['volume'].rolling(window=20).std()
        
        def calc_tod_z(row):
            stats = time_stats.get(row['time'])
            if stats and pd.notna(stats['std']) and stats['std'] > 0:
                return (row['volume'] - stats['mean']) / stats['std']
            if pd.notna(row['rolling_std']) and row['rolling_std'] > 0:
                return (row['volume'] - row['rolling_mean']) / row['rolling_std']
            return 0.0
            
        df['vol_z_score'] = df.apply(calc_tod_z, axis=1)
        df.drop(columns=['time', 'rolling_mean', 'rolling_std'], inplace=True, errors='ignore')
        
        # 3. Chaikin Money Flow (CMF)
        df['cmf'] = ta.cmf(df['high'], df['low'], df['close'], df['volume'], length=20)
        
        # Cleanly handle newly generated NaN values
        df.bfill(inplace=True)
        df.dropna(inplace=True)
        
        return df

    @staticmethod
    def calc_macro_geometry(df: pd.DataFrame) -> dict:
        """
        Calculates Phase 2.3 Macro-Geometric Scanner metrics.
        Returns a dictionary of boolean flags and price levels.
        """
        geometry_payload = {
            "double_bottom": False,
            "double_top": False,
            "head_and_shoulders": False,
            "levels": {}
        }
        
        # Vector Safety: ensure enough candles to confirm peaks with order=5
        if len(df) < 50:
            return geometry_payload
            
        try:
            closes = df['close'].values
            
            # 1. Extrema Detection
            # order=5 means 5 points on each side. The last 5 candles cannot be confirmed.
            peaks_idx = argrelextrema(closes, np.greater, order=5)[0]
            valleys_idx = argrelextrema(closes, np.less, order=5)[0]
            
            # 2. Double Bottom Scanner
            if len(valleys_idx) >= 2:
                v1, v2 = closes[valleys_idx[-2]], closes[valleys_idx[-1]]
                if abs(v2 - v1) / max(v1, v2) <= 0.002:
                    geometry_payload["double_bottom"] = True
                    geometry_payload["levels"]["double_bottom_level"] = round(float((v1 + v2) / 2), 2)
                    
            # 3. Double Top Scanner
            if len(peaks_idx) >= 2:
                p1, p2 = closes[peaks_idx[-2]], closes[peaks_idx[-1]]
                if abs(p2 - p1) / max(p1, p2) <= 0.002:
                    geometry_payload["double_top"] = True
                    geometry_payload["levels"]["double_top_level"] = round(float((p1 + p2) / 2), 2)
                    
            # 4. Head & Shoulders Scanner
            if len(peaks_idx) >= 3 and len(valleys_idx) >= 2:
                p1, p2, p3 = closes[peaks_idx[-3]], closes[peaks_idx[-2]], closes[peaks_idx[-1]]
                if p2 > p1 and p2 > p3:
                    if abs(p1 - p3) / max(p1, p3) <= 0.01:
                        geometry_payload["head_and_shoulders"] = True
                        geometry_payload["levels"]["head_and_shoulders_neckline"] = round(float(min(p1, p3)), 2)
                        
        except Exception:
            pass
            
        return geometry_payload

    @staticmethod
    def calc_micro_candlesticks(df: pd.DataFrame) -> dict:
        """
        Calculates Phase 2.4 Micro-Candlestick Matrix.
        Returns a dictionary of active patterns for the latest candle.
        """
        if df is None or df.empty or len(df) < 2:
            return {"active_patterns": "None"}
            
        op = df['open'].values
        hi = df['high'].values
        lo = df['low'].values
        cl = df['close'].values
        
        # Calculate patterns using fast C-optimized TA-lib
        patterns = {
            "engulfing": talib.CDLENGULFING(op, hi, lo, cl)[-1],
            "hammer": talib.CDLHAMMER(op, hi, lo, cl)[-1],
            "shooting_star": talib.CDLSHOOTINGSTAR(op, hi, lo, cl)[-1],
            "morning_star": talib.CDLMORNINGSTAR(op, hi, lo, cl)[-1],
            "evening_star": talib.CDLEVENINGSTAR(op, hi, lo, cl)[-1],
            "doji": talib.CDLDOJI(op, hi, lo, cl)[-1]
        }
        
        def map_signal(val):
            if val == 100: return "Bullish"
            if val == -100: return "Bearish"
            return None
            
        # Map values to human readable strings and filter inactive ones
        active = {k: map_signal(v) for k, v in patterns.items() if map_signal(v) is not None}
        
        if not active:
            return {"active_patterns": "None"}
            
        return active

    @staticmethod
    def calc_camarilla_pivots(htf_df: pd.DataFrame) -> dict:
        """
        Calculates Camarilla Pivot Points based on Yesterday's Daily Candle.
        """
        pivots = {"H4": 0.0, "H3": 0.0, "L3": 0.0, "L4": 0.0}
        if htf_df is None or len(htf_df) < 2:
            return pivots
            
        try:
            # Extract Yesterday's candle (second to last)
            yest = htf_df.iloc[-2]
            hi, lo, cl = float(yest['high']), float(yest['low']), float(yest['close'])
            r = hi - lo
            
            pivots["H4"] = round(cl + (r * 1.1 / 2), 2)
            pivots["H3"] = round(cl + (r * 1.1 / 4), 2)
            pivots["L3"] = round(cl - (r * 1.1 / 4), 2)
            pivots["L4"] = round(cl - (r * 1.1 / 2), 2)
        except Exception:
            pass
            
        return pivots

    @staticmethod
    def calc_htf_trend(htf_df: pd.DataFrame) -> str:
        """
        Determines Higher Timeframe trend via Daily 9-EMA.
        """
        if htf_df is None or htf_df.empty:
            return "Neutral"
            
        try:
            df = htf_df.copy()
            df['ema_9'] = ta.ema(df['close'], length=9)
            df.bfill(inplace=True)
            df.dropna(inplace=True)
            if df.empty:
                return "Neutral"
            
            last_row = df.iloc[-1]
            if last_row['close'] > last_row['ema_9']:
                return "Bullish"
            else:
                return "Bearish"
        except Exception:
            return "Neutral"

    @staticmethod
    def calc_relative_strength(stock_df: pd.DataFrame, index_df: pd.DataFrame) -> float:
        """
        Calculates 50-period Comparative Relative Strength vs Nifty 50.
        """
        if stock_df is None or index_df is None or stock_df.empty or index_df.empty:
            return 0.0
            
        try:
            if len(stock_df) < 50 or len(index_df) < 50:
                return 0.0
                
            stock_pct = (stock_df['close'].iloc[-1] - stock_df['close'].iloc[-50]) / stock_df['close'].iloc[-50]
            index_pct = (index_df['close'].iloc[-1] - index_df['close'].iloc[-50]) / index_df['close'].iloc[-50]
            
            return round((stock_pct - index_pct) * 100, 2)
        except Exception:
            return 0.0

    @staticmethod
    def generate_omni_dataframes(df_5m: pd.DataFrame) -> dict:
        """
        Module 1: The Omni-Resampler
        Resamples the base 5-minute dataframe up to 15m, 30m, 1h, and 4h.
        """
        if df_5m is None or df_5m.empty:
            return {}
            
        df = df_5m.copy()
        if 'timestamp' in df.columns:
            df.set_index('timestamp', inplace=True)
            
        agg_dict = {
            'open': 'first',
            'high': 'max',
            'low': 'min',
            'close': 'last',
            'volume': 'sum'
        }
        
        omni = {}
        try:
            for freq, label in [('5min', '5m'), ('15min', '15m'), ('30min', '30m'), ('1h', '1h'), ('4h', '4h')]:
                omni[label] = df.resample(freq).agg(agg_dict).dropna()
        except Exception as e:
            import logging
            logging.getLogger(__name__).error(f"Error resampling omni dataframes: {e}")
            
        return omni

    @staticmethod
    def calc_omni_metrics(omni_dfs: dict) -> dict:
        """
        Module 2: The Omni-Calculator
        Calculates RSI, MACD, EMAs, and ATR for all 5 DataFrames.
        """
        results = {}
        for tf, df in omni_dfs.items():
            if df.empty or len(df) < 1:
                continue
                
            try:
                temp_df = df.copy()
                temp_df['ema_9'] = ta.ema(temp_df['close'], length=9)
                temp_df['ema_21'] = ta.ema(temp_df['close'], length=21)
                temp_df['rsi_14'] = ta.rsi(temp_df['close'], length=14)
                
                macd = ta.macd(temp_df['close'], fast=12, slow=26, signal=9)
                if macd is not None:
                    temp_df['macd'] = macd['MACD_12_26_9']
                    temp_df['macd_hist'] = macd['MACDh_12_26_9']
                else:
                    temp_df['macd'] = 0.0
                    temp_df['macd_hist'] = 0.0
                    
                temp_df['atr_14'] = ta.atr(temp_df['high'], temp_df['low'], temp_df['close'], length=14)
                
                bbands = ta.bbands(temp_df['close'], length=20, std=2)
                if bbands is not None and not bbands.empty and len(bbands.columns) >= 3:
                    temp_df['bb_lower'] = bbands.iloc[:, 0]
                    temp_df['bb_upper'] = bbands.iloc[:, 2]
                else:
                    temp_df['bb_lower'] = 0.0
                    temp_df['bb_upper'] = 0.0
                
                latest = temp_df.iloc[-1]
                
                def safe_float(val):
                    return 0.0 if pd.isna(val) else round(float(val), 2)
                    
                results[tf] = {
                    'rsi': safe_float(latest.get('rsi_14')),
                    'ema_9': safe_float(latest.get('ema_9')),
                    'ema_21': safe_float(latest.get('ema_21')),
                    'macd': safe_float(latest.get('macd')),
                    'macd_hist': safe_float(latest.get('macd_hist')),
                    'atr': safe_float(latest.get('atr_14')),
                    'bb_lower': safe_float(latest.get('bb_lower')),
                    'bb_upper': safe_float(latest.get('bb_upper'))
                }
            except Exception as e:
                import logging
                logging.getLogger(__name__).error(f"Error calculating omni metrics for {tf}: {e}")
                
        return results

    @staticmethod
    def generate_signal_payload(df: pd.DataFrame, htf_df: pd.DataFrame, token: str, index_df: pd.DataFrame = None) -> dict:
        """
        Executes math engine on a copy of the dataframe, extracts the latest row,
        and returns a clean dictionary payload.
        """
        df_copy = df.copy()
        
        if df_copy.empty:
            return {"token": token, "error": "Not enough data"}
            
        processed_df = MathEngine.calc_trend_and_momentum(df_copy)
        if processed_df.empty:
            return {"token": token, "error": "Not enough data"}
            
        processed_df = MathEngine.calc_institutional_volume(processed_df)
        if processed_df.empty:
            return {"token": token, "error": "Not enough data"}
            
        geometry = MathEngine.calc_macro_geometry(processed_df)
        candlesticks = MathEngine.calc_micro_candlesticks(processed_df)
        camarilla = MathEngine.calc_camarilla_pivots(htf_df)
        htf_trend = MathEngine.calc_htf_trend(htf_df)
        comparative_rs = MathEngine.calc_relative_strength(htf_df, index_df)
        
        # Phase 11.B: Omni-Timeframe Synthesis Engine
        omni_dfs = MathEngine.generate_omni_dataframes(df_copy)
        omni_metrics = MathEngine.calc_omni_metrics(omni_dfs)
        
        last_row = processed_df.iloc[-1]
        
        def safe_float(val):
            return 0.0 if pd.isna(val) else round(float(val), 2)
            
        payload = {
            "token": token,
            "macd_hist_5m": safe_float(last_row.get('macd_hist', 0)),
            "macd_signal_5m": safe_float(last_row.get('macd_signal', 0)),
            "bb_lower_5m": safe_float(last_row.get('bb_lower', 0)),
            "bb_upper_5m": safe_float(last_row.get('bb_upper', 0)),
            "vwap_5m": safe_float(last_row.get('vwap', 0)),
            "vwap_lower_5m": safe_float(last_row.get('vwap_lower', 0)),
            "vwap_upper_5m": safe_float(last_row.get('vwap_upper', 0)),
            "vol_z_score_5m": safe_float(last_row.get('vol_z_score', 0)),
            "cmf_5m": safe_float(last_row.get('cmf', 0)),
            "rsi_5m": safe_float(last_row.get('rsi_14', 50)),
            "geometry": geometry,
            "candlesticks": candlesticks,
            "camarilla": camarilla,
            "htf_trend": htf_trend,
            "comparative_rs": comparative_rs
        }
        
        # Flatten Omni metrics into the root level of the payload clearly labeled by timeframe
        for tf, metrics in omni_metrics.items():
            for key, val in metrics.items():
                payload[f"{key}_{tf}"] = val
                
        # Calculate and inject 1D metrics from htf_df directly
        if htf_df is not None and not htf_df.empty:
            htf_copy = htf_df.copy()
            htf_processed = MathEngine.calc_trend_and_momentum(htf_copy)
            if not htf_processed.empty:
                last_htf = htf_processed.iloc[-1]
                payload["rsi_1d"] = safe_float(last_htf.get('rsi_14'))
                payload["ema_9_1d"] = safe_float(last_htf.get('ema_9'))
                payload["ema_21_1d"] = safe_float(last_htf.get('ema_21'))
                payload["macd_1d"] = safe_float(last_htf.get('macd'))
                payload["macd_hist_1d"] = safe_float(last_htf.get('macd_hist'))
                payload["atr_1d"] = safe_float(last_htf.get('atr_14'))
                payload["bb_lower_1d"] = safe_float(last_htf.get('bb_lower'))
                payload["bb_upper_1d"] = safe_float(last_htf.get('bb_upper'))
        
        return payload

